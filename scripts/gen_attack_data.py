#!/usr/bin/env python3
"""Generate lib/AttackData.php from the official MITRE ATT&CK STIX bundle.

Usage: scripts/gen_attack_data.py enterprise-attack.json [ics-attack.json mobile-attack.json] > lib/AttackData.php
Source: https://github.com/mitre-attack/attack-stix-data (the first file is the Enterprise domain and drives coverage;
the optional ICS and Mobile files only make their technique IDs and tactic names count as real.)
"""
import json, sys


def load(path):
    d = json.load(open(path))
    objs = d['objects']
    by_id = {o['id']: o for o in objs}
    return objs, by_id


def ext(o):
    for r in o.get('external_references', []):
        if r.get('source_name') == 'mitre-attack':
            return r['external_id']
    return None


tactics, other_tactics, techs, groups, software = {}, set(), {}, set(), set()
ver = '?'
for n, path in enumerate(sys.argv[1:]):
    objs, by_id = load(path)
    if n == 0:
        coll = next(o for o in objs if o['type'] == 'x-mitre-collection')
        ver = coll.get('x_mitre_version', '?')
    for o in objs:
        if o['type'] == 'x-mitre-tactic' and not o.get('revoked') and not o.get('x_mitre_deprecated'):
            if n == 0:
                tactics[o['x_mitre_shortname']] = (ext(o), o['name'])
            else:
                other_tactics.add(o['x_mitre_shortname'])
        if o['type'] == 'attack-pattern':
            i = ext(o)
            if not i:
                continue
            status = 'revoked' if o.get('revoked') else ('deprecated' if o.get('x_mitre_deprecated') else 'active')
            techs[i] = {
                'name': o['name'], 'status': status, 'by': None, 'domain': n,
                'tactics': sorted(p['phase_name'] for p in o.get('kill_chain_phases', []) if p.get('kill_chain_name') == 'mitre-attack'),
            }
        if o['type'] == 'intrusion-set' and ext(o) and not o.get('revoked') and not o.get('x_mitre_deprecated'):
            groups.add(ext(o))
        if o['type'] in ('malware', 'tool') and ext(o) and not o.get('revoked') and not o.get('x_mitre_deprecated'):
            software.add(ext(o))
    for o in objs:
        if o['type'] == 'relationship' and o.get('relationship_type') == 'revoked-by':
            a, b = by_id.get(o['source_ref']), by_id.get(o['target_ref'])
            if a and b and a['type'] == 'attack-pattern' and b['type'] == 'attack-pattern':
                i, j = ext(a), ext(b)
                if i in techs and j:
                    techs[i]['by'] = j

groups, software = sorted(groups), sorted(software)
for i, t in techs.items():  # follow replacement chains to the id that is still active
    seen = 0
    while t['by'] and t['by'] in techs and techs[t['by']]['status'] != 'active' and techs[t['by']]['by'] and seen < 10:
        t['by'] = techs[t['by']]['by']
        seen += 1
for i, t in techs.items():
    if not t['tactics'] and '.' in i and i.split('.')[0] in techs:
        t['tactics'] = techs[i.split('.')[0]]['tactics']


def q(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"

print('<?php')
print('declare(strict_types=1);')
print()
print('namespace MitreMap;')
print()
print(f'// GENERATED by scripts/gen_attack_data.py from the official ATT&CK STIX data, Enterprise v{ver}. Do not edit by hand.')
print(f"const ATTACK_VERSION = {q(ver)};")
print()
print('/** shortname => [TA id, name] */')
print('const ATTACK_TACTICS = [')
for k, (i, n) in sorted(tactics.items(), key=lambda kv: kv[1][0]):
    print(f"    {q(k)} => [{q(i)}, {q(n)}],")
print('];')
print()
print('/** shortnames of ICS and Mobile tactics, valid as tags but not used for coverage */')
print('const ATTACK_OTHER_TACTICS = [' + ', '.join(q(x) for x in sorted(other_tactics - set(tactics))) + '];')
print()
print('/** technique id => [name, [tactics], status, replacement or null, domain (0 enterprise, 1 ics, 2 mobile)] */')
print('const ATTACK_TECHNIQUES = [')
for i in sorted(techs):
    t = techs[i]
    tac = ', '.join(q(x) for x in t['tactics'])
    by = q(t['by']) if t['by'] else 'null'
    print(f"    {q(i)} => [{q(t['name'])}, [{tac}], {q(t['status'])}, {by}, {t['domain']}],")
print('];')
print()
print('const ATTACK_GROUPS = [' + ', '.join(q(x) for x in groups) + '];')
print('const ATTACK_SOFTWARE = [' + ', '.join(q(x) for x in software) + '];')
